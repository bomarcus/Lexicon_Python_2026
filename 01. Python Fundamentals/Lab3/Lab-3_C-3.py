# calculate the sum of a list using a loop.
# create list with numbers
list_of_numbers = [
    1,
    3,
    5,
    6,
    7,
    10
]
# create a sum var.
total = 0
# for each number in the list add number to total.
for number in list_of_numbers:
    total += number
# 3 print total
print(total)
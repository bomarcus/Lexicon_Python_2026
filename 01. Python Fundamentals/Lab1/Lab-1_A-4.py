number_1 = 10
number_2 = 5

# addition
print(number_1, "plus", number_2, "is", number_1 + number_2)
# subtraction
print(number_1, "minus", number_2, "is", number_1 - number_2)
# multiplication
print(number_1, "times", number_2, "is", number_1 * number_2)
# division
print(number_1, "divided by", number_2, "is", number_1 / number_2)
# floor division
print("the floor quotient of", number_1, "divided by", number_2, "is", number_1 // number_2)
# remainder / modulo
print("the remainder of", number_1, "divided by", number_2, "is", number_1 % number_2)
# exponentiation
print(number_1, "to the power of", number_2, "is", number_1 ** number_2)
print("\n")
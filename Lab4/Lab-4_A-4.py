# demonstrate parameters vs arguemnt

# define greet_person function with parameter "name"
# return name 
def greet_person(name): # parameter
    print("Hello", name)

# define introduction function with parameters "name" and "city" 
def introduce(name, city):
    print(name, "lives in", city)

greet_person("bo") # argument
introduce("bo", "stockholm") # arguments